const MAX_CUSTOM_OVERRIDE_BYTES = 64 * 1024
const MAX_SNAPSHOT_BYTES = 8 * 1024 * 1024
const MAX_SNAPSHOT_FILES = 2_000

export type SnapshotSummary = {
	id: string
	createdAt: number
	reason: string
	upstreamVersion: string
	sizeBytes: number
	encryptedWith: 'device' | 'passphrase'
}

function compareSemver(first: string, second: string): number {
	const parse = (value: string) => {
		const [core, prerelease] = value.split('-', 2)
		const parts = core.split('.').map((part) => Number(part.replace(/\D.*$/, '')) || 0)
		return {parts, prerelease: prerelease ?? ''}
	}
	const a = parse(first)
	const b = parse(second)
	for (let index = 0; index < 3; index++) {
		if (a.parts[index] !== b.parts[index]) return a.parts[index] > b.parts[index] ? 1 : -1
	}
	if (a.prerelease === b.prerelease) return 0
	if (!a.prerelease) return 1
	if (!b.prerelease) return -1
	return a.prerelease > b.prerelease ? 1 : -1
}

function minutesOfDay(date: Date): number {
	return date.getHours() * 60 + date.getMinutes()
}

function withinWindow(window: {days: number[]; start: string; end: string}, now = new Date()): boolean {
	if (!window.days.includes(now.getDay())) return false
	const [startHour, startMinute] = window.start.split(':').map(Number)
	const [endHour, endMinute] = window.end.split(':').map(Number)
	const start = startHour * 60 + startMinute
	const end = endHour * 60 + endMinute
	const current = minutesOfDay(now)
	if (start === end) return true
	return start < end ? current >= start && current < end : current >= start || current < end
}

/**
 * Power-user app runtime controls that live outside the app directory, so an
 * app update (which rewrites docker-compose.yml) cannot erase them.
 */
export class AppOverrideManager {
	readonly directory: string
	#config: ConfigStore
	#audit: AuditLog
	#umbreld: UmbrelLike
	#logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}

	constructor(input: {
		dataDirectory: string
		config: ConfigStore
		audit: AuditLog
		umbreld: UmbrelLike
		logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}
	}) {
		this.directory = path.join(input.dataDirectory, 'app-overrides')
		this.#config = input.config
		this.#audit = input.audit
		this.#umbreld = input.umbreld
		this.#logger = input.logger
	}

	pathFor(appId: string): {quota: string; custom: string} {
		if (!/^[a-zA-Z0-9-_]{1,80}$/.test(appId)) throw new HttpError(400, 'Invalid app id')
		const directory = path.join(this.directory, appId)
		return {
			quota: path.join(directory, 'docker-compose.override.yml'),
			custom: path.join(directory, 'docker-compose.umbra-custom.yml'),
		}
	}

	#renderQuota(quota: AppQuota, services: string[]): string {
		if (!services.length) return ''
		const lines = ['# Generated by Umbra. Changes are overwritten.', 'services:']
		for (const service of services) {
			lines.push(`  ${JSON.stringify(service)}:`)
			if (quota.cpus !== undefined) lines.push(`    cpus: ${quota.cpus}`)
			if (quota.memoryMb !== undefined) lines.push(`    mem_limit: ${JSON.stringify(`${quota.memoryMb}m`)}`)
			if (quota.pids !== undefined) lines.push(`    pids_limit: ${quota.pids}`)
			// Docker has no per-container VRAM quota. Reservation is recorded as a
			// compose label so tooling and the UI can show intent; the NVIDIA
			// driver enforces total GPU memory, not per-process slices.
			if (quota.vramMb !== undefined) {
				lines.push(`    labels:`)
				lines.push(`      io.umbra.vram-quota-mb: ${JSON.stringify(String(quota.vramMb))}`)
			}
		}
		return `${lines.join('\n')}\n`
	}

	async #serviceNames(appId: string): Promise<string[]> {
		try {
			const app = this.#umbreld.apps.getApp(appId)
			const compose = (await app.readCompose?.()) as {services?: Record<string, unknown>} | undefined
			return Object.keys(compose?.services ?? {}).filter((service) => service !== 'app_proxy')
		} catch {
			return []
		}
	}

	async apply(appId: string, actor?: {id: string; name?: string}): Promise<{applied: boolean; services: number}> {
		const config = await this.#config.load()
		const override = config.extras.overrides[appId]
		const paths = this.pathFor(appId)
		if (!override || (!override.composeOverride && Object.keys(override.quota).length === 0)) {
			await removeIfExists(paths.quota)
			await removeIfExists(paths.custom)
			return {applied: false, services: 0}
		}
		const services = await this.#serviceNames(appId)
		const quotaYaml = this.#renderQuota(override.quota, services)
		if (quotaYaml) await writeFileAtomic(paths.quota, quotaYaml, 0o600)
		else await removeIfExists(paths.quota)
		if (override.composeOverride) await writeFileAtomic(paths.custom, override.composeOverride, 0o600)
		else await removeIfExists(paths.custom)
		if (actor) {
			this.#audit.record({
				type: 'override.update',
				action: 'Applied app runtime overrides',
				actor: {type: 'user', id: actor.id, name: actor.name},
				target: appId,
				detail: {quota: override.quota, customBytes: Buffer.byteLength(override.composeOverride)},
			})
		}
		return {applied: true, services: services.length}
	}

	async applyAll() {
		const config = await this.#config.load()
		await Promise.all(
			Object.keys(config.extras.overrides).map((appId) =>
				this.apply(appId).catch((error) => this.#logger.error(`Failed to apply overrides for '${appId}'`, error)),
			),
		)
	}

	async save(
		appId: string,
		input: {composeOverride?: string; quota?: AppQuota},
		actor: {id: string; name?: string; ip?: string},
	) {
		if (!(await this.#umbreld.apps.isInstalled(appId))) throw new HttpError(404, 'App is not installed')
		const composeOverride = input.composeOverride ?? ''
		if (Buffer.byteLength(composeOverride) > MAX_CUSTOM_OVERRIDE_BYTES) {
			throw new HttpError(413, 'Compose override is too large')
		}
		if (/^\s*app_proxy\s*:/m.test(composeOverride)) {
			throw new HttpError(400, 'Overrides may not redefine the app_proxy service')
		}
		const quota: AppQuota = {}
		if (input.quota) {
			if (input.quota.cpus !== undefined) {
				if (typeof input.quota.cpus !== 'number' || input.quota.cpus <= 0 || input.quota.cpus > 128) {
					throw new HttpError(400, 'CPU limit must be between 0 and 128')
				}
				quota.cpus = input.quota.cpus
			}
			if (input.quota.memoryMb !== undefined) {
				if (
					typeof input.quota.memoryMb !== 'number' ||
					!Number.isInteger(input.quota.memoryMb) ||
					input.quota.memoryMb < 64 ||
					input.quota.memoryMb > 1_048_576
				) {
					throw new HttpError(400, 'Memory limit must be 64-1048576 MB')
				}
				quota.memoryMb = input.quota.memoryMb
			}
			if (input.quota.pids !== undefined) {
				if (!Number.isInteger(input.quota.pids) || input.quota.pids < 16 || input.quota.pids > 32768) {
					throw new HttpError(400, 'PID limit must be 16-32768')
				}
				quota.pids = input.quota.pids
			}
			if (input.quota.vramMb !== undefined) {
				if (!Number.isInteger(input.quota.vramMb) || input.quota.vramMb < 256) {
					throw new HttpError(400, 'VRAM reservation must be at least 256 MB')
				}
				quota.vramMb = input.quota.vramMb
			}
		}
		await this.#config.update((draft) => {
			draft.extras.overrides[appId] = {
				composeOverride,
				quota,
				updatedAt: Date.now(),
				updatedBy: actor.name ?? actor.id,
			}
		})
		const result = await this.apply(appId, actor)
		return {...result, appId, restartRequired: true}
	}

	async remove(appId: string, actor: {id: string; name?: string; ip?: string}) {
		await this.#config.update((draft) => {
			delete draft.extras.overrides[appId]
		})
		await this.apply(appId)
		this.#audit.record({
			type: 'override.update',
			action: 'Removed app runtime overrides',
			actor: {type: 'user', id: actor.id, name: actor.name, ip: actor.ip},
			target: appId,
		})
		return {ok: true, restartRequired: true}
	}
}

type SnapshotEnvelope = {
	v: 1
	alg: 'aes-256-gcm'
	id: string
	createdAt: number
	reason: string
	upstreamVersion: string
	encryptedWith: 'device' | 'passphrase'
	kdf: 'device' | 'scrypt'
	salt?: string
	iv: string
	tag: string
	data: string
	sizeBytes: number
	innerSha256: string
}

type SnapshotBundle = {
	version: 1
	createdAt: number
	upstreamVersion: string
	files: Record<string, string>
}

/**
 * Encrypted configuration snapshots. They capture what is hard to recreate
 * (umbra config, agent policies, plugin settings, overrides, per-app settings),
 * not media or app data volumes. The archive is gzipped then AES-256-GCM sealed.
 */
export class SnapshotManager {
	readonly directory: string
	#config: ConfigStore
	#secrets: SecretStore
	#audit: AuditLog
	#umbreld: UmbrelLike
	#logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}
	#timer?: NodeJS.Timeout
	#running = false

	constructor(input: {
		dataDirectory: string
		config: ConfigStore
		secrets: SecretStore
		audit: AuditLog
		umbreld: UmbrelLike
		logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}
	}) {
		this.directory = path.join(input.dataDirectory, 'snapshots')
		this.#config = input.config
		this.#secrets = input.secrets
		this.#audit = input.audit
		this.#umbreld = input.umbreld
		this.#logger = input.logger
	}

	async start() {
		await ensureDir(this.directory, 0o700)
		if (this.#timer) return
		this.#timer = setInterval(() => {
			void this.#scheduledTick().catch((error) => this.#logger.error('Scheduled snapshot failed', error))
		}, 60 * 60_000)
		this.#timer.unref?.()
	}

	async stop() {
		if (this.#timer) clearInterval(this.#timer)
		this.#timer = undefined
	}

	async #scheduledTick() {
		const config = await this.#config.load()
		if (!config.extras.snapshots.enabled) return
		const snapshots = await this.list()
		const newest = snapshots[0]?.createdAt ?? 0
		if (Date.now() - newest < config.extras.snapshots.intervalHours * 3_600_000) return
		await this.create('scheduled', {type: 'system', id: 'snapshot-scheduler'})
	}

	async #collect(): Promise<Record<string, string>> {
		const files: Record<string, string> = {}
		const add = async (relative: string, absolute: string, maxBytes = 1_000_000) => {
			try {
				const buffer = await readFile(absolute)
				if (buffer.length > maxBytes) return
				files[relative] = buffer.toString('base64')
			} catch {
				// Missing files are simply not part of this snapshot.
			}
		}
		const root = this.#umbreld.dataDirectory
		await add('umbrel.yaml', path.join(root, 'umbrel.yaml'))
		await add('umbra/config.json', path.join(root, 'umbra', 'config.json'))
		await add('umbra/agents.json', path.join(root, 'umbra', 'agents.json'))
		await add('umbra/cloudflare/config.yml', path.join(root, 'umbra', 'cloudflare', 'config.yml'))
		const overrideDirectory = path.join(root, 'umbra', 'app-overrides')
		for (const appId of await readdir(overrideDirectory).catch(() => [])) {
			if (!/^[a-zA-Z0-9-_]{1,80}$/.test(appId)) continue
			await add(`umbra/app-overrides/${appId}/docker-compose.override.yml`, path.join(overrideDirectory, appId, 'docker-compose.override.yml'))
			await add(`umbra/app-overrides/${appId}/docker-compose.umbra-custom.yml`, path.join(overrideDirectory, appId, 'docker-compose.umbra-custom.yml'))
		}
		for (const app of this.#umbreld.apps.instances) {
			await add(`app-data/${app.id}/settings.yml`, path.join(app.dataDirectory, 'settings.yml'), 256_000)
		}
		const pluginRoot = path.join(root, 'umbra', 'plugins', 'installed')
		for (const pluginId of await readdir(pluginRoot).catch(() => [])) {
			if (!/^[a-z0-9.-]{3,80}$/.test(pluginId)) continue
			for (const version of await readdir(path.join(pluginRoot, pluginId)).catch(() => [])) {
				if (!/^\d+\.\d+\.\d+/.test(version)) continue
				await add(
					`umbra/plugins/installed/${pluginId}/${version}/umbra-plugin.json`,
					path.join(pluginRoot, pluginId, version, 'umbra-plugin.json'),
					128_000,
				)
				await add(
					`umbra/plugins/installed/${pluginId}/${version}/settings.json`,
					path.join(pluginRoot, pluginId, version, 'settings.json'),
					128_000,
				)
			}
		}
		if (Object.keys(files).length > MAX_SNAPSHOT_FILES) throw new HttpError(413, 'Snapshot has too many files')
		return files
	}

	async create(
		reason: string,
		actor: {type: 'user' | 'system'; id: string; name?: string; ip?: string},
		passphrase?: string,
	): Promise<SnapshotSummary> {
		if (this.#running) throw new HttpError(409, 'A snapshot is already running')
		this.#running = true
		try {
			const config = await this.#config.load()
			const bundle: SnapshotBundle = {
				version: 1,
				createdAt: Date.now(),
				upstreamVersion: this.#umbreld.version,
				files: await this.#collect(),
			}
			const inner = gzipSync(Buffer.from(stableJson(bundle)), {level: 9})
			if (inner.length > MAX_SNAPSHOT_BYTES) throw new HttpError(413, 'Snapshot is too large')
			let sealed: SealedSecret
			let kdf: 'device' | 'scrypt' = 'device'
			let salt: string | undefined
			if (passphrase) {
				const saltBuffer = Buffer.from(randomId(16), 'hex')
				salt = saltBuffer.toString('base64')
				sealed = sealWithKey(derivePassphraseKey(passphrase, saltBuffer), inner.toString('base64'))
				kdf = 'scrypt'
			} else {
				sealed = this.#secrets.seal(inner.toString('base64'))
			}
			const id = `${new Date().toISOString().replace(/[:.]/g, '-')}-${reason.replace(/[^a-z0-9-]/gi, '').slice(0, 20) || 'manual'}`
			const envelope: SnapshotEnvelope = {
				v: 1,
				alg: 'aes-256-gcm',
				id,
				createdAt: bundle.createdAt,
				reason,
				upstreamVersion: bundle.upstreamVersion,
				encryptedWith: passphrase ? 'passphrase' : 'device',
				kdf,
				...(salt ? {salt} : {}),
				iv: sealed.iv,
				tag: sealed.tag,
				data: sealed.data,
				sizeBytes: inner.length,
				innerSha256: createHash('sha256').update(inner).digest('hex'),
			}
			await writeJsonAtomic(path.join(this.directory, `${id}.usnap.json`), envelope, 0o600)
			await this.prune(config.extras.snapshots.retention)
			this.#audit.record({
				type: 'snapshot.create',
				action: `Created encrypted configuration snapshot (${reason})`,
				actor,
				target: id,
				detail: {files: Object.keys(bundle.files).length, bytes: inner.length, kdf},
			})
			return {
				id,
				createdAt: envelope.createdAt,
				reason,
				upstreamVersion: envelope.upstreamVersion,
				sizeBytes: inner.length,
				encryptedWith: envelope.encryptedWith,
			}
		} finally {
			this.#running = false
		}
	}

	async list(): Promise<SnapshotSummary[]> {
		const entries = await readdir(this.directory).catch(() => [])
		const snapshots: SnapshotSummary[] = []
		for (const entry of entries) {
			if (!entry.endsWith('.usnap.json')) continue
			const envelope = (await readJsonOrNull(path.join(this.directory, entry))) as SnapshotEnvelope | null
			if (!envelope || envelope.v !== 1) continue
			snapshots.push({
				id: envelope.id,
				createdAt: envelope.createdAt,
				reason: envelope.reason,
				upstreamVersion: envelope.upstreamVersion,
				sizeBytes: envelope.sizeBytes,
				encryptedWith: envelope.encryptedWith,
			})
		}
		return snapshots.sort((a, b) => b.createdAt - a.createdAt)
	}

	async restore(id: string, actor: {id: string; name?: string; ip?: string}, passphrase?: string) {
		if (!/^[A-Za-z0-9._-]{1,120}$/.test(id)) throw new HttpError(400, 'Invalid snapshot id')
		const envelope = (await readJsonOrNull(path.join(this.directory, `${id}.usnap.json`))) as SnapshotEnvelope | null
		if (!envelope) throw new HttpError(404, 'Snapshot not found')
		let inner: Buffer
		try {
			const key = passphrase
				? derivePassphraseKey(passphrase, Buffer.from(envelope.salt ?? '', 'base64'))
				: this.#secrets.key
			inner = Buffer.from(openWithKey(key, envelope), 'base64')
		} catch {
			throw new HttpError(400, 'Snapshot could not be decrypted (wrong passphrase or different device)')
		}
		if (createHash('sha256').update(inner).digest('hex') !== envelope.innerSha256) {
			throw new HttpError(400, 'Snapshot integrity check failed')
		}
		const bundle = JSON.parse(gunzipSync(inner).toString('utf8')) as SnapshotBundle
		if (!isRecord(bundle.files) || bundle.version !== 1) throw new HttpError(400, 'Invalid snapshot payload')
		const root = this.#umbreld.dataDirectory
		const restored: string[] = []
		const skipped: string[] = []
		for (const [relative, encoded] of Object.entries(bundle.files)) {
			if (typeof encoded !== 'string') continue
			// Restore only Umbra-managed configuration. umbrel.yaml and app data
			// are deliberately excluded from automatic restore: overwriting them
			// live can corrupt an installed app or the account store.
			const allowed =
				relative === 'umbra/config.json' ||
				relative === 'umbra/agents.json' ||
				relative.startsWith('umbra/app-overrides/') ||
				relative.startsWith('umbra/plugins/installed/') ||
				relative.startsWith('app-data/') && relative.endsWith('/settings.yml')
			if (!allowed) {
				skipped.push(relative)
				continue
			}
			const target = path.resolve(root, relative)
			if (!target.startsWith(`${path.resolve(root)}${path.sep}`)) continue
			await writeFileAtomic(target, Buffer.from(encoded, 'base64'), 0o600)
			restored.push(relative)
		}
		this.#audit.record({
			type: 'snapshot.restore',
			action: 'Restored configuration from snapshot',
			actor: {type: 'user', id: actor.id, name: actor.name, ip: actor.ip},
			target: id,
			detail: {restored: restored.length, skipped: skipped.length},
		})
		return {restored, skipped, restartRequired: true}
	}

	async prune(retention: number): Promise<number> {
		const snapshots = await this.list()
		let removed = 0
		for (const snapshot of snapshots.slice(Math.max(1, retention))) {
			await removeIfExists(path.join(this.directory, `${snapshot.id}.usnap.json`))
			removed++
		}
		return removed
	}
}

/**
 * Maintenance-window app auto-updates. Only apps allowed by policy are touched,
 * updates run sequentially, and a configuration snapshot is taken first.
 */
export class AutoUpdateManager {
	#config: ConfigStore
	#audit: AuditLog
	#umbreld: UmbrelLike & {appStore?: {publicRegistry: () => Promise<unknown[]>}}
	#snapshots: SnapshotManager
	#logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}
	#timer?: NodeJS.Timeout
	#running = false

	constructor(input: {
		config: ConfigStore
		audit: AuditLog
		umbreld: UmbrelLike & {appStore?: {publicRegistry: () => Promise<unknown[]>}}
		snapshots: SnapshotManager
		logger: {log: (...args: unknown[]) => void; error: (...args: unknown[]) => void}
	}) {
		this.#config = input.config
		this.#audit = input.audit
		this.#umbreld = input.umbreld
		this.#snapshots = input.snapshots
		this.#logger = input.logger
	}

	start() {
		if (this.#timer) return
		this.#timer = setInterval(() => {
			void this.tick().catch((error) => this.#logger.error('Auto-update tick failed', error))
		}, 10 * 60_000)
		this.#timer.unref?.()
	}

	stop() {
		if (this.#timer) clearInterval(this.#timer)
		this.#timer = undefined
	}

	async tick(): Promise<{updated: string[]; skipped: string[]}> {
		if (this.#running) return {updated: [], skipped: ['already-running']}
		const config = await this.#config.load()
		const auto = config.extras.autoUpdate
		if (!auto.enabled) return {updated: [], skipped: ['disabled']}
		if (!withinWindow(auto.window)) return {updated: [], skipped: ['outside-window']}
		const allowed = (appId: string) => auto.apps === 'all' || auto.apps.includes(appId)
		const registry = new Map<string, {version?: string; compatible?: boolean}>()
		try {
			const repositories = (await this.#umbreld.appStore?.publicRegistry?.()) ?? []
			for (const repository of repositories as {apps?: unknown[]}[]) {
				for (const app of repository.apps ?? []) {
					if (!isRecord(app) || typeof app.id !== 'string') continue
					if (!registry.has(app.id)) {
						registry.set(app.id, {
							version: typeof app.version === 'string' ? app.version : undefined,
							compatible: typeof app.compatible === 'boolean' ? app.compatible : undefined,
						})
					}
				}
			}
		} catch (error) {
			this.#logger.error('Auto-update could not read the app store', error)
			return {updated: [], skipped: ['registry-unavailable']}
		}

		const candidates: {id: string; current: string; next: string}[] = []
		for (const app of this.#umbreld.apps.instances) {
			if (!allowed(app.id)) continue
			const latest = registry.get(app.id)
			if (!latest?.version) continue
			if (auto.onlyCompatible && latest.compatible === false) continue
			const manifest = await app.readManifest().catch(() => null)
			if (!manifest?.version) continue
			if (compareSemver(latest.version, manifest.version) > 0) {
				candidates.push({id: app.id, current: manifest.version, next: latest.version})
			}
		}
		if (!candidates.length) return {updated: [], skipped: []}

		this.#running = true
		const updated: string[] = []
		try {
			await this.#snapshots
				.create('pre-app-update', {type: 'system', id: 'auto-update'})
				.catch((error) => this.#logger.error('Pre-update snapshot failed', error))
			for (const candidate of candidates.slice(0, 3)) {
				try {
					this.#logger.log(`Auto-updating ${candidate.id} ${candidate.current} -> ${candidate.next}`)
					await this.#umbreld.apps.update(candidate.id)
					updated.push(candidate.id)
					this.#audit.record({
						type: 'update.preflight',
						action: `Auto-updated ${candidate.id} to ${candidate.next}`,
						actor: {type: 'system', id: 'auto-update'},
						target: candidate.id,
						detail: {from: candidate.current, to: candidate.next},
					})
				} catch (error) {
					this.#audit.record({
						type: 'update.preflight',
						action: `Auto-update failed for ${candidate.id}`,
						actor: {type: 'system', id: 'auto-update'},
						target: candidate.id,
						outcome: 'failure',
						detail: {message: error instanceof Error ? error.message : String(error)},
					})
				}
			}
		} finally {
			this.#running = false
		}
		return {updated, skipped: []}
	}
}

